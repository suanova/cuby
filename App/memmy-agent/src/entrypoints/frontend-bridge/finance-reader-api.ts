import crypto from "node:crypto";
import path from "node:path";
import fs from "node:fs";
import { ConsistencyReportSchema } from "@memmy/local-api-contracts";
import { FinanceProjectSchema, FinanceProjectListSchema, FinanceProjectBuildSchema, ConsistencyEditorSchema, ConsistencyExportSchema, type FinanceProject } from "@memmy/local-api-contracts";
import type { FinanceHistory } from "./finance-history.js";
import {
  FinanceCatalogSchema,
  FinanceReaderSchema,
  FinanceNotesSchema,
  FinanceRequestSchema,
  FinanceDraftSchema,
  FinanceDraftExportSchema,
} from "@memmy/local-api-contracts";

export type FinanceToolCall = (name: string, args: Record<string, unknown>) => Promise<unknown>;
export class FinanceReaderError extends Error {
  constructor(
    message: string,
    public status = 400,
  ) {
    super(message);
  }
}

/** Only fixed, explicitly enabled FinanceBuddy MCP tools can be invoked here. */
export class FinanceReaderApi {
  private handles = new Map<string, { base: string; sha: string; expires: number }>();
  private downloads = new Map<string,{file:string;root:string;sha:string;bytes:number;file_name:string;mime:string;expires:number}>();
  constructor(
    private callTool: FinanceToolCall,
    private fetchFn: typeof fetch = fetch,
    private mediaRoot?: string,
    private history?: FinanceHistory,
    private workspaceRoot?: string,
  ) {}

  private async connectProject(project:FinanceProject) {
    if(!this.history) return project;
    const receipt=await this.tool("manage_finance_project",{operation:"workspace",project_id:project.id}) as {root_path?:unknown};
    if(typeof receipt.root_path!=="string") throw new FinanceReaderError("未能連結項目資料夾。",502);
    const id=this.history.project(project,receipt.root_path);
    if(project.external_id!==id) project=FinanceProjectSchema.parse(await this.tool("manage_finance_project",{operation:"bind",project_id:project.id,external_id:id}));
    for(const version of project.versions) for(const run of version.runs) this.history.review(project,run);
    return project;
  }

  private async tool(name: "manage_finance_project" | "edit_consistency_draft" | "list_c2_reviews" | "open_c2_reader" | "build_consistency_review" | "start_consistency_semantic" | "read_consistency_review" | "read_consistency_page", args: Record<string, unknown>) {
    const raw = await this.callTool(`mcp_financebuddy_reports_${name}`, args);
    try {
      return typeof raw === "string" ? JSON.parse(raw) : raw;
    } catch {
      throw new FinanceReaderError(
        "FinanceBuddy service unavailable; check its MCP connection.",
        503,
      );
    }
  }

  async catalog() {
    return FinanceCatalogSchema.parse(await this.tool("list_c2_reviews", {}));
  }

  private async upstream(base: string, route: string, value?: unknown) {
    // URL is generated by an enabled local MCP tool, never supplied by the renderer.
    const response = await this.fetchFn(base + route, {
      method: value === undefined ? "GET" : "POST",
      redirect: "error",
      signal: AbortSignal.timeout(15_000),
      headers:
        value === undefined ? {} : { "Content-Type": "application/json", "X-Reader-Request": "1" },
      ...(value === undefined ? {} : { body: JSON.stringify(value) }),
    });
    const chunks: Uint8Array[] = [];
    let size = 0;
    if (!response.body) throw new FinanceReaderError("Empty reader response.", 502);
    const stream = response.body.getReader();
    try {
      while (true) {
        const next = await stream.read();
        if (next.done) break;
        size += next.value.byteLength;
        if (size > 8 * 1024 * 1024) {
          await stream.cancel();
          throw new FinanceReaderError("Reader response too large.", 502);
        }
        chunks.push(next.value);
      }
    } finally {
      stream.releaseLock();
    }
    const data = Buffer.concat(chunks);
    if (!response.ok) {
      let message = "Reader request failed; reopen the review.";
      try {
        message = JSON.parse(data.toString("utf8")).error || message;
      } catch {
        /* fixed fallback */
      }
      throw new FinanceReaderError(message, response.status === 409 ? 409 : 502);
    }
    return { data, type: response.headers.get("content-type") ?? "" };
  }

  async request(raw: unknown): Promise<unknown> {
    const parsed = FinanceRequestSchema.safeParse(raw);
    if (!parsed.success) throw new FinanceReaderError("Invalid report reader request.");
    const input = parsed.data;
    if (input.action === "project-list") {
      const result=FinanceProjectListSchema.parse(await this.tool("manage_finance_project",{operation:"list"}));
      for(let i=0;i<result.projects.length;i++) result.projects[i]=await this.connectProject(result.projects[i]);
      return result;
    }
    if (input.action === "project-session") {
      const binding=this.history?.lookup(input.session_key)??null;
      if(binding) {
        const project=FinanceProjectSchema.parse(await this.tool("manage_finance_project",{operation:"read",project_id:binding.project_id}));
        if(project.external_id!==binding.native_project_id || !project.versions.some(v=>v.runs.includes(binding.run_id)))
          throw new FinanceReaderError("審閱紀錄已變更，請重新開啟項目。",409);
      }
      return {binding};
    }
    if (input.action === "project-open") {
      if(!this.history) throw new FinanceReaderError("請更新 Cuby 項目紀錄支援。",503);
      const project=await this.connectProject(FinanceProjectSchema.parse(await this.tool("manage_finance_project",{operation:"read",project_id:input.project_id})));
      return {binding:this.history.review(project,input.run_id)};
    }
    if (input.action === "project-create") {
      const {action,...args}=input;
      return this.connectProject(FinanceProjectSchema.parse(await this.tool("manage_finance_project",{operation:"create",...args})));
    }
    if (input.action === "project-save") {
      if (input.documents) this.validateUploads(input.documents);
      if (input.documents && input.run_id) throw new FinanceReaderError("請選上載或沿用底稿其中一種來源。");
      const {action,...args}=input;
      return this.connectProject(FinanceProjectSchema.parse(await this.tool("manage_finance_project",{operation:"save",...args})));
    }
    if (input.action === "project-build") {
      const {action,...args}=input;
      const result=FinanceProjectBuildSchema.parse(await this.tool("manage_finance_project",{operation:"build",...args}));
      result.project=await this.connectProject(result.project);
      return result;
    }
    if (input.action === "consistency-editor" || input.action === "consistency-suggest") {
      const {action,...args}=input;
      return ConsistencyEditorSchema.parse(await this.tool("edit_consistency_draft",{operation:action==="consistency-editor"?"read":"suggest",...args}));
    }
    if (input.action === "consistency-decide") {
      const {action,operation,...args}=input;
      return ConsistencyEditorSchema.parse(await this.tool("edit_consistency_draft",{operation:"update",operation_decision:operation,...args}));
    }
    if (input.action === "consistency-draft-page") {
      const {action,...args}=input;
      const result=await this.tool("edit_consistency_draft",{operation:"render",...args}) as Record<string,unknown>;
      this.checkLayout(result);
      if (typeof result.data_url!=="string" || result.data_url.length>8*1024*1024 || !result.data_url.startsWith("data:image/png;base64,iVBORw0KGgo"))
        throw new FinanceReaderError("修訂PDF頁面無效。",502);
      return {data_url:result.data_url,revision:result.revision,layout_notice:result.layout_notice};
    }
    if (input.action === "consistency-draft-export") {
      const {action,...args}=input;
      const result=await this.tool("edit_consistency_draft",{operation:"export",...args}) as Record<string,unknown>;
      this.checkLayout(result);
      return this.grantDownload(input.run_id,result);
    }
    if (input.action === "consistency-semantic-start")
      return ConsistencyReportSchema.parse(await this.tool("start_consistency_semantic", {run_id:input.run_id}));
    if (input.action === "consistency-build") {
      if (input.documents) {
        if (!this.mediaRoot || new Set(input.documents.map(d => d.slot)).size !== 4)
          throw new FinanceReaderError("請為四個位置各選一份已上載的 PDF。");
        const root = fs.realpathSync(this.mediaRoot);
        for (const doc of input.documents) {
          const real = fs.realpathSync(doc.path);
          const relative = path.relative(root, real);
          if (!relative || relative.startsWith("..") || path.isAbsolute(relative) || path.extname(real).toLowerCase() !== ".pdf")
            throw new FinanceReaderError("只能使用 Cuby 本次上載的 PDF。");
        }
      }
      return ConsistencyReportSchema.parse(await this.tool("build_consistency_review", {
        fiscal_year: input.fiscal_year, ...(input.comparisons ? {comparisons:input.comparisons} : {}), ...(input.documents ? {documents:input.documents} : {}),
      }));
    }
    if (input.action === "consistency-read")
      return ConsistencyReportSchema.parse(await this.tool("read_consistency_review", {run_id:input.run_id,full:true}));
    if (input.action === "consistency-page") {
      const {action, ...args} = input;
      const image = await this.tool("read_consistency_page", args) as {data_url?:unknown};
      if (typeof image.data_url !== "string" || image.data_url.length > 8*1024*1024 || !image.data_url.startsWith("data:image/png;base64,iVBORw0KGgo"))
        throw new FinanceReaderError("Invalid consistency PDF page.",502);
      return {data_url:image.data_url};
    }
    if (input.action === "open") {
      const receipt = (await this.tool("open_c2_reader", {
        review_path: input.review_path,
      })) as Record<string, unknown>;
      if (input.artifact_path) {
        const normalize = (value: string) =>
          process.platform === "win32" ? path.resolve(value).toLowerCase() : path.resolve(value);
        if (
          typeof receipt?.review_path !== "string" ||
          normalize(input.artifact_path) !== normalize(receipt.review_path)
        ) {
          throw new FinanceReaderError(
            "This attachment belongs to a different workspace. Open its own review tool.",
            409,
          );
        }
      }
      const base = receipt?.reader_url;
      if (
        typeof base !== "string" ||
        !/^http:\/\/127\.0\.0\.1:[1-9][0-9]{0,4}$/.test(base) ||
        +new URL(base).port > 65535
      ) {
        throw new FinanceReaderError(
          "The installed reader returned an invalid local address.",
          502,
        );
      }
      const health = JSON.parse((await this.upstream(base, "/api/health")).data.toString("utf8"));
      if (health.app !== "financebuddy-review-reader")
        throw new FinanceReaderError("Reader identity mismatch.", 502);
      const review = FinanceReaderSchema.parse(
        JSON.parse((await this.upstream(base, "/api/review")).data.toString("utf8")),
      );
      const notes = FinanceNotesSchema.parse(
        JSON.parse((await this.upstream(base, "/api/decisions")).data.toString("utf8")),
      );
      if (
        health.review_sha256 !== review.review_sha256 ||
        notes.review_sha256 !== review.review_sha256
      ) {
        throw new FinanceReaderError("Reader revision mismatch.", 502);
      }
      for (const [key, handle] of this.handles)
        if (handle.expires < Date.now()) this.handles.delete(key);
      if (this.handles.size >= 16) this.handles.delete(this.handles.keys().next().value!);
      const handle = crypto.randomUUID();
      this.handles.set(handle, {
        base,
        sha: review.review_sha256,
        expires: Date.now() + 8 * 60 * 60_000,
      });
      return { handle, review, notes };
    }
    const handle = this.handles.get(input.handle);
    if (!handle || handle.expires < Date.now())
      throw new FinanceReaderError("Reader expired. Reopen this workpaper.", 410);
    const route =
      input.action === "page" || input.action === "rule"
        ? `/api/${input.action}/${input.page}.png`
        : input.action === "draft-save"
          ? "/api/drafts"
          : input.action === "save"
            ? "/api/decisions"
            : `/api/${input.action}`;
    const { data, type } = await this.upstream(
      handle.base,
      route,
      input.action === "save" || input.action === "draft-save" ? input.value : undefined,
    );
    if (input.action === "page" || input.action === "rule") {
      if (
        !type.startsWith("image/png") ||
        data.subarray(0, 8).toString("hex") !== "89504e470d0a1a0a"
      )
        throw new FinanceReaderError("Invalid PDF page response.", 502);
      return { data_url: `data:image/png;base64,${data.toString("base64")}` };
    }
    if (input.action === "draft-export") {
      const result = FinanceDraftExportSchema.parse(JSON.parse(data.toString("utf8")));
      if (result.review_sha256 !== handle.sha || result.draft.review_sha256 !== handle.sha)
        throw new FinanceReaderError("Draft revision changed.", 409);
      return result;
    }
    if (input.action.endsWith("export")) return { text: data.toString("utf8") };
    const result =
      input.action === "review"
        ? FinanceReaderSchema.parse(JSON.parse(data.toString("utf8")))
        : input.action === "drafts" || input.action === "draft-save"
          ? FinanceDraftSchema.parse(JSON.parse(data.toString("utf8")))
          : FinanceNotesSchema.parse(JSON.parse(data.toString("utf8")));
    if (result.review_sha256 !== handle.sha)
      throw new FinanceReaderError("Reader revision changed. Reopen the workpaper.", 409);
    return result;
  }

  private checkLayout(result:Record<string,unknown>) {
    if(result.status!=="blocked") return;
    const issues=Array.isArray(result.issues)?result.issues:[];
    const issue=issues[0] as {slot?:string;page?:number;reason?:string}|undefined;
    const labels:Record<string,string>={esg_en:"ESG英文",esg_zh:"ESG中文",annual_en:"年報英文",annual_zh:"年報中文"};
    throw new FinanceReaderError((labels[issue?.slot??""]??"PDF")+(issue?.page?"第"+issue.page+"頁":"")+"："+(issue?.reason??"未能保留原版面，請調整新寫法。"),409);
  }

  private readDownload(value:{file:string;root:string;sha:string;bytes:number;mime:string}) {
    try {
      const root=fs.realpathSync(value.root),real=fs.realpathSync(value.file),relative=path.relative(root,real);
      if(!relative || relative.startsWith("..") || path.isAbsolute(relative) || path.resolve(value.file)!==real)
        throw new Error("path");
      const stat=fs.statSync(real);
      if(!stat.isFile() || stat.size!==value.bytes || stat.size>128*1024*1024) throw new Error("size");
      const data=fs.readFileSync(real);
      if(crypto.createHash("sha256").update(data).digest("hex")!==value.sha) throw new Error("hash");
      if(value.mime==="application/pdf"?data.subarray(0,5).toString()!=="%PDF-":data.subarray(0,4).toString("hex")!=="504b0304") throw new Error("type");
      return data;
    } catch {throw new FinanceReaderError("匯出檔案已變更，請重新匯出。",409);}
  }

  private grantDownload(run:string,result:Record<string,unknown>) {
    if(!this.workspaceRoot || typeof result.file_path!=="string" || typeof result.file_name!=="string" ||
       !/^[A-Za-z0-9_.-]+$/.test(result.file_name) || !Number.isInteger(result.revision) ||
       (result.revision as number)<0 || typeof result.bytes!=="number" || !Number.isInteger(result.bytes) ||
       result.bytes<=0 || result.bytes>128*1024*1024 || typeof result.sha256!=="string" ||
       !/^[a-f0-9]{64}$/.test(result.sha256) || !["application/pdf","application/zip"].includes(String(result.mime)) ||
       !result.file_name.endsWith(result.mime==="application/pdf"?".pdf":".zip"))
      throw new FinanceReaderError("匯出PDF資料無效。",502);
    const root=fs.realpathSync(this.workspaceRoot);
    const expected=path.join(root,"outputs","consistency",run,"exports","r"+result.revision,result.file_name);
    if(path.resolve(result.file_path)!==expected) throw new FinanceReaderError("匯出文件位置不符。",502);
    const grant={file:expected,root,sha:result.sha256,bytes:result.bytes,file_name:result.file_name,mime:String(result.mime),expires:Date.now()+10*60_000};
    this.readDownload(grant);
    for(const [id,value] of this.downloads) if(value.expires<Date.now()) this.downloads.delete(id);
    if(this.downloads.size>=16) this.downloads.delete(this.downloads.keys().next().value!);
    const id=crypto.randomUUID();
    const receipt=ConsistencyExportSchema.parse({...result,download_id:id});
    this.downloads.set(id,grant);
    return receipt;
  }

  download(id:string) {
    const value=this.downloads.get(id);
    if(!value || value.expires<Date.now()) {this.downloads.delete(id);throw new FinanceReaderError("下載已過期，請重新匯出。",410);}
    return {data:this.readDownload(value),file_name:value.file_name,mime:value.mime};
  }

  private validateUploads(documents:{slot:string;path:string}[]) {
    if (!this.mediaRoot || new Set(documents.map(d=>d.slot)).size!==4) throw new FinanceReaderError("請選四份已上載的 PDF。");
    const root=fs.realpathSync(this.mediaRoot);
    for (const doc of documents) {
      const real=fs.realpathSync(doc.path),relative=path.relative(root,real);
      if (!relative || relative.startsWith("..") || path.isAbsolute(relative) || path.extname(real).toLowerCase()!==".pdf") throw new FinanceReaderError("只能儲存 Cuby 已上載的 PDF。");
    }
  }
}
